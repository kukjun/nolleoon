import test from 'node:test';
import assert from 'node:assert/strict';
import {travelGameHttpFixture} from '../support/travel-game-http-fixture.mjs';
test('trial ten-minute facilitator transfer preserves administrator, defendant and electorate; only new facilitator opens voting',async t=>{
 const f=await travelGameHttpFixture(t);
 let run=(await f.create('trial',{caseText:'합성 사건',penaltyText:'합성 벌칙',durationMinutes:3,defendantMembershipId:f.ids.b})).body;
 const path=f.root+'/runs/'+run.runId;
 const command=async(actor,action)=>{const current=(await f.call(path,actor)).body;return f.call(path+'/actions',actor,{requestId:f.id(),expectedVersion:current.version,command:action});};
 run=(await command('b',{action:'consent',decision:'accepted'})).body;
 run=(await f.call(path+'/start','a',{requestId:f.id(),expectedVersion:run.version})).body;
 assert.equal(run.game.phase,'defense');
 assert.equal((await command('b',{action:'begin-vote'})).status,403);
 assert.equal((await command('c',{action:'begin-vote'})).status,403);
 const frozen=f.db().prepare('SELECT membership_id FROM travel_run_participants WHERE run_id=? ORDER BY membership_id').all(run.runId);
 f.setNow(16000);await f.call(f.root,'b');await f.call(f.root,'c');
 f.setNow(615999);await f.call(f.root,'b');await f.call(f.root,'c');
 assert.equal((await f.call(path,'c')).body.facilitatorMembershipId,f.ids.a);
 f.setNow(616000);run=(await f.call(path,'c')).body;
 assert.equal(run.facilitatorMembershipId,f.ids.c);
 assert.equal(run.game.defendantMembershipId,f.ids.b);
 assert.equal(run.game.consent,'accepted');
 assert.equal((await f.call(f.root,'c')).body.members.find(x=>x.isAdmin).membershipId,f.ids.a);
 assert.deepEqual(f.db().prepare('SELECT membership_id FROM travel_run_participants WHERE run_id=? ORDER BY membership_id').all(run.runId),frozen);
 assert.equal((await command('a',{action:'begin-vote'})).status,403);
 assert.equal((await command('b',{action:'begin-vote'})).status,403);
 run=(await command('c',{action:'begin-vote'})).body;
 assert.equal(run.game.phase,'voting');assert.equal(run.game.deadline,796000);
 assert.equal(run.facilitatorMembershipId,f.ids.c);
});
