import {test,expect} from '@playwright/test';

test('@travel-e2e real account deletion redacts all-author trial prose and room restore does not resurrect it',async({browser,baseURL})=>{test.setTimeout(60000);
const contexts=[];
let seq=0;
try{for(const subject of [1901,1902,1903]){const c=await browser.newContext({baseURL,viewport:{width:390,height:844}});
contexts.push(c);
const l=await c.request.post('/api/account/login',{headers:{origin:baseURL,'x-trip-court-request':'1'},data:{returnTo:'/travel'}});
const state=new URL((await l.json()).authorizationUrl).searchParams.get('state');
expect((await c.request.get(`/api/account/callback?state=${state}&code=synthetic-${subject}`)).status()).toBe(200);
}const[a,b,c]=contexts;
const post=async(actor,path,data)=>{const r=await actor.request.post(path,{headers:{origin:baseURL,'x-trip-court-request':'1'},data});
expect(r.status(),await r.text()).toBe(201);
return r.json();
};
const get=async(actor,path)=>{const r=await actor.request.get(path);
expect(r.status()).toBe(200);
return r.json();
};
const id=()=>`delete-e2e-${++seq}`;
await post(a,'/api/account/profile',{expectedRevision:0,displayName:'삭제될이름',presetId:'preset-01'});
let room=await post(a,'/api/travel-rooms',{requestId:id(),title:'정책 검증 여행',startDate:null,endDate:null});
const root='/api/travel-rooms/'+room.roomId;
const own=room.self.membershipId;
const invite=await post(a,root+'/invite',{requestId:id(),expectedVersion:room.version});
const joined=await post(b,'/api/travel-invites/'+invite.inviteToken+'/join',{requestId:id()});
const nextAdmin=joined.self.membershipId;
await post(c,'/api/travel-invites/'+invite.inviteToken+'/join',{requestId:id()});
room=await get(a,root);
let run=await post(a,root+'/runs',{requestId:id(),expectedVersion:room.version,type:'trial',selectedMembershipIds:room.members.map(m=>m.membershipId),settings:{caseText:'삭제할 비밀 사건',penaltyText:'삭제할 비밀 벌칙',durationMinutes:3,defendantMembershipId:own}});
const runPath=root+'/runs/'+run.runId;
const action=async(actor,command)=>{run=await get(actor,runPath);
run=await post(actor,runPath+'/actions',{requestId:id(),expectedVersion:run.version,command});
};
await action(a,{action:'consent',decision:'accepted'});
run=await post(a,runPath+'/start',{requestId:id(),expectedVersion:run.version});
await action(a,{action:'defense',decision:'submit',text:'삭제할 비밀 변론'});
await action(a,{action:'begin-vote'});
await action(b,{action:'vote',choice:'guilty',reason:'다른 작성자 비밀 이유'});
await action(c,{action:'vote',choice:'guilty',reason:'세 번째 비밀 이유'});
expect(run.status).toBe('completed');
room=await get(a,root);
await post(a,root+'/administrator',{requestId:id(),expectedVersion:room.version,membershipId:nextAdmin});
const pa=await a.newPage();
await pa.goto('/travel');
await pa.getByRole('button',{name:'프로필 수정'}).click();
await pa.getByRole('button',{name:'계정 탈퇴 안내'}).click();
await pa.getByLabel('확인 문구').fill('계정 탈퇴');
const deletionResponse=pa.waitForResponse(r=>r.url().endsWith('/api/account/delete'));
await pa.getByRole('button',{name:'계정 영구 탈퇴'}).click();
expect((await deletionResponse).status()).toBe(201);
await expect(pa.getByRole('button',{name:'카카오로 로그인'})).toBeVisible();
expect(await (await a.request.get('/api/account/session')).json()).toEqual({authenticated:false});
const redacted=await get(b,runPath);
expect(redacted.game.redacted).toBe(true);
expect(redacted.game.summary.rounds[0].guilty).toBe(2);
for(const text of ['삭제할 비밀','다른 작성자 비밀','세 번째 비밀','삭제될이름'])expect(JSON.stringify(redacted)).not.toContain(text);
const pb=await b.newPage();
await pb.goto('/travel/rooms/'+room.roomId);
await pb.getByRole('button',{name:'이 여행의 게임 기록'}).click();
await pb.getByRole('button',{name:/우리끼리 재판/}).click();
await expect(pb.getByRole('heading',{name:'참가자 탈퇴로 상세가 삭제됐어요'})).toBeVisible();
await pb.screenshot({path:'artifacts/deletion-ui/real-redacted-trial-390.png',fullPage:true});
await pb.getByRole('button',{name:'결과 확인 · 로비로'}).click();
await pb.getByRole('button',{name:'여행방 로비로',exact:true}).click();
await pb.locator('summary').filter({hasText:'방 관리 ·'}).click();
await pb.getByRole('button',{name:'여행방 삭제 안내'}).click();
await pb.getByRole('button',{name:'여행방 삭제 확인',exact:true}).click();
await expect(pb.getByRole('heading',{name:'내 여행방'})).toBeVisible();
expect((await c.request.get(root)).status()).toBe(403);
await pb.getByRole('button',{name:'삭제한 여행방',exact:true}).click();
await pb.getByRole('button',{name:'복구 안내'}).click();
await pb.getByRole('button',{name:'여행방 복구 확인'}).click();
await expect(pb.getByRole('heading',{name:'정책 검증 여행'})).toBeVisible();
expect((await get(c,runPath)).game.redacted).toBe(true);
expect((await get(c,root)).members).toHaveLength(2);
await pb.screenshot({path:'artifacts/deletion-ui/real-room-restored-390.png',fullPage:true});
}finally{for(const c of contexts)await c.close().catch(()=>{});
}});

