import {test} from 'node:test';
import assert from 'node:assert/strict';
import {isRoomSnapshot,verifiedVoteSnapshot} from '../../apps/web/src/api/rooms-client.ts';
test('방 DTO 런타임 검증은 개인 필드·잘못된 방장·중복 멤버를 거부한다',()=>{
 const room={closed:false,interruption:null,interrupted:false,start:{canStart:false,missing:[]},game:null,consent:{penaltyRevision:0,roleRevision:0,decisionVersion:0,status:'pending',defendantMemberId:null,canDecide:false},roleRevision:0,rosterEditable:true,draft:{version:0,caseText:'',penaltyText:'',durationMinutes:3},version:1,roomId:'room',inviteCode:'code',self:{memberId:'one',isHost:true},members:[{memberId:'one',role:'participant',nickname:'나',isHost:true,connected:true}]};
 assert.equal(isRoomSnapshot(room),true);
 assert.equal(isRoomSnapshot({...room,closed:true,self:{memberId:'one',isHost:false},members:[]}),true);
 assert.equal(isRoomSnapshot({...room,closed:true}),false);
 assert.equal(isRoomSnapshot({...room,closed:undefined}),false);
 assert.equal(isRoomSnapshot({...room,interruption:{caseText:'허용 사건'}}),true);
 assert.equal(isRoomSnapshot({...room,interruption:{caseText:'허용 사건',reason:'private'}}),false);
 assert.equal(isRoomSnapshot({...room,members:[...room.members,{...room.members[0],memberId:'two',nickname:'다른 방장'}]}),false);
 assert.equal(isRoomSnapshot({...room,interrupted:undefined}),false);
 assert.equal(isRoomSnapshot({...room,self:{memberId:'one',isHost:false},members:[{...room.members[0],isHost:false}]}),true);
 const game={publishedRounds:[],settlement:null,ownVote:null,version:0,serverNow:1000,round:null,defense:{roundNumber:1,status:'pending',text:null},gameId:'game',status:'defense',caseText:'사건',penaltyText:'벌칙',durationMinutes:3,self:{role:'observer',eligible:false},participantCount:5,voterCount:4};
 assert.equal(isRoomSnapshot({...room,game}),true);
 const published={number:1,counts:{guilty:1,notGuilty:1,abstain:0},reasons:[{choice:'guilty',reason:'공개 이유'}]};
 assert.equal(isRoomSnapshot({...room,game:{...game,publishedRounds:[published]}}),true);
 assert.equal(isRoomSnapshot({...room,game:{...game,publishedRounds:[{...published,reasons:[{choice:'guilty',reason:'이유',memberId:'private'}]}]}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,publishedRounds:[published,published]}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,defense:{...game.defense,roundNumber:3}}}),false);
 const settlement={roundNumber:1,outcome:'tie',guilty:1,notGuilty:1,abstain:0,total:2,closedAt:2000,closedBy:'all-submitted'};
 assert.equal(isRoomSnapshot({...room,game:{...game,settlement}}),true);
 assert.equal(isRoomSnapshot({...room,game:{...game,settlement:{...settlement,outcome:['tie']}}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,settlement:{...settlement,total:3}}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,settlement:{...settlement,reasons:['private']}}}),false);
 const command={kind:'vote',gameId:'game',roundNumber:1,requestId:'request',choice:'guilty',reason:' 이유 '};
 const voteResponse={snapshot:{...room,game:{...game,round:{number:2,startedAt:1000,deadline:2000}}},receipt:{gameId:'game',roundNumber:1,choice:'guilty',reason:'이유'}};
 assert.equal(verifiedVoteSnapshot(voteResponse,command)?.game.ownVote,null);
 assert.equal(verifiedVoteSnapshot({...voteResponse,receipt:{...voteResponse.receipt,roundNumber:2}},command),null);
 assert.equal(verifiedVoteSnapshot({...voteResponse,receipt:{...voteResponse.receipt,reason:'다른 이유'}},command),null);
 assert.equal(verifiedVoteSnapshot({...voteResponse,receipt:{...voteResponse.receipt,private:'secret'}},command),null);

 const ownVote={roundNumber:1,choice:'abstain',reason:''};
 assert.equal(isRoomSnapshot({...room,game:{...game,ownVote}}),true);
 assert.equal(isRoomSnapshot({...room,game:{...game,ownVote:{...ownVote,choice:['abstain']}}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,ownVote:{...ownVote,voterId:'private'}}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,status:['defense']}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,defense:{status:['pending'],text:null}}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,serverNow:'1000'}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,round:{number:1,startedAt:1000,deadline:900}}}),false);
 assert.equal(isRoomSnapshot({...room,consent:{...room.consent,status:['pending']}}),false);
 for(const status of [['defense'],{}, {toString:()=> 'defense'},null,0,true])assert.equal(isRoomSnapshot({...room,game:{...game,status}}),false);
 for(const role of [['observer'],{}, {toString:()=> 'observer'},null,0,true])assert.equal(isRoomSnapshot({...room,game:{...game,self:{...game.self,role}}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,self:{role:'observer',eligible:true}}}),false);
 assert.equal(isRoomSnapshot({...room,game:{...game,sessionId:'private'}}),false);
 assert.equal(isRoomSnapshot({...room,start:{canStart:'yes',missing:[]}}),false);
 assert.equal(isRoomSnapshot({...room,game:{sessionId:'private'}}),false);
 assert.equal(isRoomSnapshot({...room,consent:{...room.consent,status:'unknown'}}),false);
 for(const status of [['accepted'],{}, {toString:()=> 'accepted'},null,0,true])assert.equal(isRoomSnapshot({...room,consent:{...room.consent,status}}),false);
 for(const key of ['penaltyRevision','roleRevision','decisionVersion'])for(const value of ['0',[0],{},null,true])assert.equal(isRoomSnapshot({...room,consent:{...room.consent,[key]:value}}),false);
 assert.equal(isRoomSnapshot({...room,consent:{...room.consent,decisionVersion:-1}}),false);
 assert.equal(isRoomSnapshot({...room,consent:{...room.consent,token:'private'}}),false);
 assert.equal(isRoomSnapshot({...room,roleRevision:-1}),false);
 assert.equal(isRoomSnapshot({...room,rosterEditable:'yes'}),false);
 assert.equal(isRoomSnapshot({...room,members:[{...room.members[0],role:'plaintiff'}]}),false);
 assert.equal(isRoomSnapshot({...room,draft:{...room.draft,durationMinutes:0}}),false);
 assert.equal(isRoomSnapshot({...room,draft:{...room.draft,version:-1}}),false);
 assert.equal(isRoomSnapshot({...room,draft:{...room.draft,secret:'private'}}),false);
 assert.equal(isRoomSnapshot({...room,version:-1}),false);
 assert.equal(isRoomSnapshot({...room,members:[{...room.members[0],connected:undefined}]}),false);
 assert.equal(isRoomSnapshot({...room,sessionId:'private'}),false);
 assert.equal(isRoomSnapshot({...room,members:[{...room.members[0],sessionId:'private'}]}),false);
 assert.equal(isRoomSnapshot({...room,members:[...room.members,...room.members]}),false);
 assert.equal(isRoomSnapshot({...room,self:{memberId:'missing',isHost:false}}),false);
 assert.equal(isRoomSnapshot({...room,members:[{...room.members[0],isHost:false}]}),false);
 assert.equal(isRoomSnapshot({...room,self:{memberId:'one',isHost:false}}),false);
 assert.equal(isRoomSnapshot({...room,members:[]}),false);
});
